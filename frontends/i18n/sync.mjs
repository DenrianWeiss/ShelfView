// Generates the platform copies of frontends/i18n/catalog.json.
// The JSON file is the single source of truth; run `node sync.mjs` after edits.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

export function loadCatalog() {
  return JSON.parse(readFileSync(join(here, 'catalog.json'), 'utf8'));
}

export function renderWeb(catalog) {
  return `// Generated by frontends/i18n/sync.mjs from catalog.json. Do not edit.\n` +
    `export const catalog = ${JSON.stringify(catalog, null, 2)};\n`;
}

export function renderApple(catalog) {
  return JSON.stringify(catalog, null, 2) + '\n';
}

export function artifacts(catalog = loadCatalog()) {
  return [
    { path: join(here, '..', 'web', 'i18n-catalog.mjs'), content: renderWeb(catalog) },
    { path: join(here, '..', 'apple', 'Sources', 'BControlCore', 'Resources', 'catalog.json'), content: renderApple(catalog) },
  ];
}

export function checkArtifacts(catalog = loadCatalog()) {
  const stale = [];
  for (const artifact of artifacts(catalog)) {
    let current = null;
    try { current = readFileSync(artifact.path, 'utf8'); } catch { /* missing */ }
    if (current !== artifact.content) stale.push(artifact.path);
  }
  return stale;
}

export function sync({ check = false } = {}) {
  const stale = checkArtifacts();
  if (check) return stale;
  for (const artifact of artifacts()) {
    mkdirSync(dirname(artifact.path), { recursive: true });
    writeFileSync(artifact.path, artifact.content);
  }
  return [];
}

const invoked = process.argv[1] ? resolve(process.argv[1]) : '';
if (invoked === resolve(fileURLToPath(import.meta.url))) {
  const check = process.argv.includes('--check');
  const stale = sync({ check });
  if (check && stale.length) {
    console.error('Generated i18n artifacts are stale; run: node frontends/i18n/sync.mjs');
    for (const path of stale) console.error(`  ${path}`);
    process.exitCode = 1;
  } else {
    console.log(check ? 'i18n artifacts are up to date.' : 'i18n artifacts updated.');
  }
}
